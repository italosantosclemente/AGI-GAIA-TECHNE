"""The record as W3C PROV-O (JSON-LD).

Provenance tools already exist for asking where a result came from; exporting
the common world in PROV lets them ask it of this record, without trusting the
runtime that wrote it. The mapping:

- each claim is a `prov:Entity`, attributed (`prov:wasAttributedTo`) to its
  source and generated by the run that exposed it (`prov:Activity`), which was
  associated with the person who brought the task;
- a claim built on another claim `prov:wasDerivedFrom` it, a revision
  `prov:wasRevisionOf` the claim it revises;
- corrections and verifications are activities associated with the person who
  made them that `prov:used` the claim; a refuted claim is
  `prov:wasInvalidatedBy` the correction that refuted it;
- people are `prov:Person`, the runtime is a `prov:SoftwareAgent`.
"""

from __future__ import annotations

from typing import Any, Dict, List

from ..koinos.common_world import CommonWorld
from ..metatheory.replay import replay

CONTEXT = {
    "prov": "http://www.w3.org/ns/prov#",
    "gt": "https://github.com/italosantosclemente/AGI-GAIA-TECHNE#",
}


def export(world: CommonWorld) -> Dict[str, Any]:
    proj = replay(world)
    graph: List[Dict[str, Any]] = []
    agents = set()

    def agent(name: str) -> str:
        agents.add(name)
        return f"gt:agent/{name}"

    for e in world.entries():
        p = e.payload
        if e.kind == "claim":
            run = f"gt:run/{e.index}"
            graph.append({"@id": run, "@type": "prov:Activity", "prov:endedAtTime": e.at,
                          "prov:wasAssociatedWith": [{"@id": agent(e.author)}, {"@id": agent(p["requested_by"])}]})
            node = {"@id": f"gt:claim/{p['claim_id']}", "@type": "prov:Entity", "prov:value": p["content"],
                    "prov:wasAttributedTo": {"@id": agent(e.author)}, "prov:wasGeneratedBy": {"@id": run},
                    "gt:entry": e.index, "gt:end": p["end"]}
            if p.get("depends_on"):
                node["prov:wasDerivedFrom"] = [{"@id": f"gt:claim/{d}"} for d in p["depends_on"]]
            if p.get("revises"):
                node["prov:wasRevisionOf"] = {"@id": f"gt:claim/{p['revises']}"}
            graph.append(node)
        elif e.kind in ("correction", "verification"):
            act = {"@id": f"gt:{e.kind}/{e.index}", "@type": "prov:Activity", "prov:endedAtTime": e.at,
                   "prov:wasAssociatedWith": {"@id": agent(e.author)},
                   "prov:used": {"@id": f"gt:claim/{p['claim_id']}"}, "gt:entry": e.index}
            if e.kind == "correction":
                act["gt:upheld"] = p["upheld"]
                act["gt:procedure"] = p["procedure"]
            graph.append(act)
    for c in proj.claims:
        if c.refuted:
            last = next((i for i in range(len(world) - 1, -1, -1)
                         if world.entries()[i].kind == "correction" and world.entries()[i].payload["claim_id"] == c.claim_id
                         and not world.entries()[i].payload["upheld"]), None)
            if last is not None:
                for node in graph:
                    if node["@id"] == f"gt:claim/{c.claim_id}":
                        node["prov:wasInvalidatedBy"] = {"@id": f"gt:correction/{last}"}
        if c.premises_fallen:
            for node in graph:
                if node["@id"] == f"gt:claim/{c.claim_id}":
                    node["gt:premisesFallen"] = list(c.premises_fallen)
    for name in sorted(agents):
        kind = "prov:SoftwareAgent" if name in proj.machine_authors else "prov:Person"
        graph.append({"@id": f"gt:agent/{name}", "@type": kind, "gt:name": name})
    return {"@context": CONTEXT, "@graph": graph}
